// Compile assembly/selcall.ts to WebAssembly and embed it as base64 in
// src/decoder/wasm.gen.ts, so the decoder loads synchronously everywhere
// (browser, tests). Run by the pre* npm scripts; the output is git-ignored.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const out = join(mkdtempSync(join(tmpdir(), "selcall-")), "selcall.wasm");
execFileSync("npx", ["asc", "assembly/selcall.ts", "-O3", "--noAssert", "--runtime", "incremental", "-o", out], { stdio: "inherit" });
const b64 = readFileSync(out).toString("base64");
writeFileSync("src/decoder/wasm.gen.ts", `// Generated by scripts/build-wasm.mjs from assembly/selcall.ts. Do not edit.\nexport default "${b64}";\n`);
console.log(`wasm: ${Math.round((b64.length * 3) / 4 / 1024)} KB`);
